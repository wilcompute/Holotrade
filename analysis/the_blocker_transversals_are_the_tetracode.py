"""
The nine minimum blockers at a point of W(3,3) drop nine pencil transversals,
and those nine words are the TETRACODE. A bridge to the other track, which has
a hundred files of tetracode machinery and none of them about blocking.

WHERE THIS STARTS.  the_blocker_triples_are_the_small_orbit.py (4a45d15) shows
a minimum blocker B with centre c keeps eight of the twelve neighbours of c,
dropping a transversal of the pencil at c -- one point on each of the four
lines through c. the_minimum_blocker_labels_are_octets.py (aa42b38, 6f35762)
supplies the count: nine blockers per centre, 360 = 40 x 9 in all. So each
centre carries NINE transversals of a 4 x 3 grid, out of 3^4 = 81 available.
Which nine was never asked.

THE MEASUREMENT THAT FORCED THE QUESTION.  Over all C(360,2) = 64620 pairs of
minimum blockers, |B n B'| takes the values

    0    1    2    3    4    5    6    8
 4320 8640 18540 8640 12960 1440 8640 1440

and the value 5 occurs 1440 times -- which is exactly 40 x C(9,2), the number
of SAME-CENTRE pairs. Sorting by centre confirms it: same-centre pairs give 5
every single time with no spread at all, and 5 never occurs across centres (nor
does 7). So |B n B'| = 5 is a test for sharing a centre.

WHY THAT IS A CODING STATEMENT.  Two blockers at the same centre have disjoint
far triples, since the nine far triples partition the 27 far points, so the
whole intersection lives in the near part. Each near part is the twelve
neighbours minus a four-point transversal, so

    |B n B'| = 12 - |drop u drop'| = 4 + |drop n drop'|.

The measured constant 5 therefore says |drop n drop'| = 1 for every pair: any
two of the nine transversals agree in EXACTLY ONE of the four positions. Label
the three non-c points of each pencil line by F_3 and a transversal becomes a
word in F_3^4. Nine words, length four, pairwise Hamming distance exactly three.

THAT CODE IS THE TETRACODE.  A (4, 9, 3) code over an alphabet of size 3 meets
the Singleton bound, so it is MDS, equivalently an orthogonal array OA(9,4,3,2)
-- verified here: every pair of coordinates sees all nine symbol pairs. Such a
code is unique up to monomial equivalence, and after relabelling symbols within
each position the nine words form a LINEAR [4,2,3]_3 code which is SELF-DUAL.
The self-dual [4,2,3]_3 code is the tetracode. Checked at all 40 centres; and
PSp(4,3) is transitive on the 40 points, so one centre would have sufficed.

At centre 0 the words come out linear on the nose, generated by (0,1,1,1) and
(1,0,1,2):

    0000  0111  0222  1012  1120  1201  2021  2102  2210

CROSS-TRACK, WHICH IS THE POINT.  The tetracode appears in 102 files of the
W33-Theory track -- the BT1837 quotient hunt, the BT930 isometry matrix, the E8
selector aperture tables -- and in ZERO files of this one. Not one of those 102
mentions blockers, blocking sets or pencils. This is the join: the object that
track uses to organise E8 selector data is sitting inside the minimum blockers
of W(3,3), one copy per point, and the copy is canonical because the nine
blockers at a centre are canonical.

WHAT IS AND IS NOT CLAIMED.  The classification of the 360, the count nine per
centre, and the 45 octets are all prior work and are cited, not re-derived. The
uniqueness of a (4,9,3)_3 MDS code and its identification with the tetracode
are classical coding theory. What is new is the identification itself, the
intersection census that produced it, and the fact that |B n B'| = 5
characterises a shared centre. Searched the literature on codes and blocking
sets in generalised quadrangles and found no statement of it; that is a
negative search over a space that is large, so it is reported as such and not
as proof of novelty.

SCOPE.  Exhaustive: all 360 blockers, all 64620 pairs, all 40 centres. tau_2 is
untouched and stays open in [111, 115].
"""

import argparse
import collections
import itertools
import json
