Q = 3
N = 40
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def geometry():
    def nm(v):
        i = next(k for k, x in enumerate(v) if x % Q)
        z = pow(v[i] % Q, -1, Q)
        return tuple((z * x) % Q for x in v)

    def form(u, v):
        return (u[0] * v[1] - u[1] * v[0] + u[2] * v[3] - u[3] * v[2]) % Q

    pts = sorted({nm(v) for v in itertools.product(range(Q), repeat=4) if any(v)})
    idx = {v: i for i, v in enumerate(pts)}
    lines = set()
    for a, b in itertools.combinations(range(N), 2):
        if form(pts[a], pts[b]):
            continue
        S = set()
        for x in range(Q):
            for y in range(Q):
                if x or y:
                    S.add(idx[nm(tuple((x * pts[a][k] + y * pts[b][k]) % Q
                                       for k in range(4)))])
        if len(S) == 4:
            lines.add(tuple(sorted(S)))
    lines = sorted(lines)
    thru = [[i for i, L in enumerate(lines) if p in L] for p in range(N)]
    return lines, thru


def blockers_at(c, lines, thru):
    """The nine minimum blockers at c, each as (set, dropped transversal word).

    Uses the foot-collapse selector of the_blocker_triples_are_the_small_orbit.
    """
    perp = {y for i in thru[c] for y in lines[i]}
    far = sorted(set(range(N)) - perp)
    pencil = [[p for p in lines[i] if p != c] for i in thru[c]]
    pos = {p: (k, s) for k, L in enumerate(pencil) for s, p in enumerate(L)}
    edges = set()
    for L in lines:
        for x in itertools.combinations(sorted(set(L) & set(far)), 2):
            edges.add(frozenset(x))
    out = []
    for T in itertools.combinations(far, 3):
        if any(frozenset(x) in edges for x in itertools.combinations(T, 2)):
            continue
        feet = collections.Counter()
        for i in {i for p in T for i in thru[p]}:
            feet[[y for y in lines[i] if y in perp][0]] += 1
        if sorted(feet.values()) != [3, 3, 3, 3]:
            continue
        word = [None] * 4
        for x in feet:
            k, s = pos[x]
            word[k] = s
        near = [p for L in pencil for p in L if p not in set(feet)]
        B = frozenset(near) | frozenset(T)
        assert len(B) == 11 and all(B & set(L) for L in lines)
        out.append((B, tuple(word)))
    return out


def tetracode_form(words):
    """Relabel symbols within each position to make the code linear; test
    self-duality. Returns (linear, selfdual, the linear code)."""
    for origin in words:
        sh = [tuple((w[k] - origin[k]) % Q for k in range(4)) for w in words]
        for perm in itertools.product(itertools.permutations(range(Q)), repeat=4):
            if any(p[0] != 0 for p in perm):        # relabelling must fix 0
                continue
            C = {tuple(perm[k][w[k]] for k in range(4)) for w in sh}
            if len(C) != 9:
                continue
            if not all(tuple((x[k] + y[k]) % Q for k in range(4)) in C
                       for x in C for y in C):
                continue
            sd = all(sum(a[k] * b[k] for k in range(4)) % Q == 0
                     for a in C for b in C)
            return True, sd, sorted(C)
    return False, False, None


