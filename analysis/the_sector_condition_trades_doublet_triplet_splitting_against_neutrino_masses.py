    checks["lifetime_exceeds_hyperk_reach"] = p["tau_low_yr"] / p["hyperk_yr"] > 1e4
    checks["dim4_and_dim5_already_absent"] = p["dim4_absent_in"] > 0 and p["dim5_absent_in"] == 86
