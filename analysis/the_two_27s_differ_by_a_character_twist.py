Q = 3


def frames_module():
    p = os.path.join(ROOT, "analysis", "the_27_factorisation_frames_carry_the_so10_weights.py")
    spec = importlib.util.spec_from_file_location("frames27", p)
    mod = importlib.util.module_from_spec(spec)
