    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()

    fm = frames_module()
    pts, idx, nm, n, tlines, octs, halves = fm.geometry()
    disj = [[not (octs[i] & octs[j]) for j in range(45)] for i in range(45)]
    frames = []

    def ext(cur, s):
        if len(cur) == 5:
            frames.append(tuple(cur))
            return
        for j in range(s, 45):
            if all(disj[j][i] for i in cur):
                ext(cur + [j], j + 1)
    ext([], 0)

    def sfv(u, v):
        return (u[0] * v[2] - u[2] * v[0] + u[1] * v[3] - u[3] * v[1]) % Q

    def mat_perm(M):
        return tuple(idx[nm(tuple(sum(M[r][c] * pts[p][c] for c in range(4)) % Q for r in range(4)))]
                     for p in range(n))

    def tv(v):
        return [[((1 if r == c else 0) + sfv(tuple(1 if k == c else 0 for k in range(4)), v) * v[r]) % Q
                 for c in range(4)] for r in range(4)]

    def comp(a, b):
        return tuple(a[b[i]] for i in range(n))

    I = tuple(range(n))

    def closure(gs, cap=None):
        H, dq = {I}, deque([I])
        while dq:
            x = dq.popleft()
            for g in gs:
                y = comp(g, x)
                if y not in H:
                    H.add(y)
                    dq.append(y)
                    if cap and len(H) > cap:
                        return None
        return frozenset(H)

    def inv(g):
        r = [0] * n
        for i, v in enumerate(g):
            r[v] = i
        return tuple(r)

    def order(g):
        k, h = 1, g
        while h != I:
            h = comp(g, h)
            k += 1
        return k

