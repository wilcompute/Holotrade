#!/usr/bin/env python3
"""First genuinely noncommutative attack on the depth-five seed cover.

The full depth-five quotient is a set cover with 5,294 seed/leaf orbits and
6,129 tile orbits.  Subgroup-induced LP cuts leave the relaxation unchanged at
12.671477..., so this script changes relaxations rather than subgroups.

PAIRWISE CONFLICT GRAPH.
Two tile orbits are *co-coverable* when some seed orbit covers both.  The set of
tiles covered by one seed is therefore a clique in the co-coverability graph H.
Any k-seed cover induces a clique cover of H, equivalently a k-colouring of its
conflict complement C. Hence

    depth5 seeds >= chi(C) >= omega(C),
    depth5 seeds >= theta(H).

The integer packing model below searches omega(C): choose tile orbits so that
no seed orbit covers two chosen tiles.  Any feasible packing is an exact lower
bound even if the maximisation times out.  In parallel a small induced
Lovasz-theta SDP is solved numerically as an exploratory (not rigorous) probe.

TERWILLIGER ALGEBRA.
For the W33 point graph we build the subconstituent/Terwilliger algebra at one
point, generated by A and the three dual distance idempotents E_i*.  Its exact
algebra and centre dimensions, plus a generic central spectrum on the standard
40-space, are frozen.  This is the local noncommutative algebra intended for a
future block-diagonal Schrijver/N+ relaxation.

The theta value is explicitly labelled numerical unless independently replaced
by a rational PSD certificate.  The packing bound is exact.
"""
