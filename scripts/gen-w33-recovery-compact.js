#!/usr/bin/env node
"use strict";

const fs=require("node:fs");
const path=require("node:path");
const S=require("../js/substrate.js");

const root=path.resolve(__dirname,"..");
const outPath=path.join(root,"rtl/build/w33_recovery_two_stage_core_compact.v");
fs.mkdirSync(path.dirname(outPath),{recursive:true});

const pls=Array.from({length:40},()=>[]);
S.LINES.forEach((L,li)=>L.forEach((p)=>pls[p].push(li)));
for(const x of pls) x.sort((a,b)=>a-b);

const adjRows=[];
const edgeLines=[];
for(let p=0;p<40;p++){
  const pairs=[];
  for(const li of pls[p]) for(const q of S.LINES[li]) if(q!==p) pairs.push([q,li]);
  pairs.sort((a,b)=>a[0]-b[0]);
  if(pairs.length!==12||new Set(pairs.map((x)=>x[0])).size!==12) throw new Error(`bad adjacency row ${p}`);
  adjRows.push(pairs.map((x)=>x[0])); edgeLines.push(pairs.map((x)=>x[1]));
}

function hex40(n){return `40'h${n.toString(16).padStart(10,"0")}`;}
function pointLineMask(p){let m=0n;for(const li of pls[p])m|=1n<<BigInt(li);return m;}

const pointCases=Array.from({length:40},(_,p)=>`6'd${p}: plmask=${hex40(pointLineMask(p))};`).join("\n");
const nbrCases=[]; const lineCases=[];
for(let p=0;p<40;p++) for(let k=0;k<12;k++){
  const key=p*16+k;
  nbrCases.push(`10'd${key}: nbr=6'd${adjRows[p][k]};`);
  lineCases.push(`10'd${key}: edge_line=6'd${edgeLines[p][k]};`);
}
const occLines=S.LINES.map((L,li)=>{
  const sum=L.map((p)=>`busy[${p}]`).join("+");
  return `occv=${sum}; zero_lines[${li}]=(occv==0); single_lines[${li}]=(occv==1);`;
}).join("\n");

const v=`\`default_nettype none
// Generated by scripts/gen-w33-recovery-compact.js from js/substrate.js.
// Exact optimization: with F fixed for one decision,
//   F_after = F + s1(source) - z(destination) - refill,
// so candidate ordering needs only delta, then s1, then labels.  The exact
// adjacency table reduces the search from 40x40 labelled pairs to 40x12 edges.
module w33_recovery_two_stage_core_compact(
 input wire clk,input wire rst,input wire load_entry,input wire advance,
 input wire block_in,input wire [5:0] residual_lo,input wire [5:0] residual_hi,
 input wire [39:0] busy,
 output reg valid,output reg entry_q,output reg block_q,
 output reg [5:0] from,output reg [5:0] to,output reg [5:0] free_after);
reg [39:0] zero_lines,single_lines; reg [2:0] occv;
integer p,k,q,li,F,s1,z,refill,delta;
reg [39:0] pm,qm; reg best_valid; integer best_delta,best_s1,best_from,best_to;
wire [5:0] entry_source = block_q ? residual_hi : residual_lo;
function [39:0] plmask; input [5:0] x; begin case(x)
${pointCases}
default: plmask=40'b0; endcase end endfunction
function [5:0] nbr; input [5:0] p0; input [3:0] k0; reg [9:0] key; begin key={p0,k0}; case(key)
${nbrCases.join("\n")}
default: nbr=6'd0; endcase end endfunction
function [5:0] edge_line; input [5:0] p0; input [3:0] k0; reg [9:0] key; begin key={p0,k0}; case(key)
${lineCases.join("\n")}
default: edge_line=6'd0; endcase end endfunction
function integer pop40; input [39:0] x; integer j; begin pop40=0; for(j=0;j<40;j=j+1) pop40=pop40+x[j]; end endfunction
always @* begin zero_lines=0; single_lines=0;
${occLines}
end
always @* begin
 from=0;to=0;free_after=0;best_valid=0;best_delta=-99;best_s1=-1;best_from=63;best_to=63;F=pop40(zero_lines);
 for(p=0;p<40;p=p+1) begin
  pm=plmask(p); s1=pop40(single_lines & pm);
  if(busy[p] && (!entry_q || p==entry_source)) begin
   for(k=0;k<12;k=k+1) begin
    q=nbr(p,k); li=edge_line(p,k);
    if(!busy[q]) begin
     qm=plmask(q); z=pop40(zero_lines & qm); refill=single_lines[li]; delta=s1-z-refill;
     if(!best_valid || delta>best_delta || (delta==best_delta && (s1>best_s1 || (s1==best_s1 && (p<best_from || (p==best_from && q<best_to)))))) begin
      best_valid=1;best_delta=delta;best_s1=s1;best_from=p;best_to=q;
     end
    end
   end
  end
 end
 if(best_valid) begin from=best_from[5:0];to=best_to[5:0];free_after=(F+best_delta);end
end
always @(posedge clk) begin
 if(rst) begin valid<=0;entry_q<=0;block_q<=0; end
 else begin
  if(load_entry) begin valid<=1;entry_q<=1;block_q<=block_in; end
  else if(advance && valid) entry_q<=0;
 end
end
endmodule
\`default_nettype wire
`;
fs.writeFileSync(outPath,v);
console.log(JSON.stringify({status:"PASS",output:path.relative(root,outPath),directedCandidates:480,baselineLabelledPairs:1600}));
